/* total: 9984 bytes = 39 tiles */
/* 1. Each of the 11 records decodes bit-exact against chardma.py's
 *    output for the same real compressed bytes, using the dictionary
 *    fetched from the SAME synthetic gfx buffer (dict bytes placed right
 *    before the record's own compressed bytes) -- exercising the
 *    bit7-dictionary-lookup path, not just the literal/RLE paths. */
static void sub_a_per_record(void) {
    g_ran++;

    uint32_t golden_off = 0;

    for (uint32_t i = 0; i < CG_060A_RECORD_COUNT; i++) {
        const Cg060aTestRecord* rec = &kRecords[i];

        /* Synthetic gfx buffer: dict at [0,256), record bytes right after. */
        uint32_t buf_size = 256 + rec->compressed_len;
        uint8_t* buf = (uint8_t*)malloc(buf_size);
        uint8_t* dest = (uint8_t*)malloc(rec->decoded_len);

        if (buf == NULL || dest == NULL) {
            fprintf(stderr, "[test_cps3_chardma] malloc failed for record %u (buf_size=%u, decoded_len=%u)\n", i,
                    buf_size, rec->decoded_len);
            free(buf);
            free(dest);
            abort();
        }

        memcpy(buf, kDict, 256);
        memcpy(buf + 256, rec->compressed, rec->compressed_len);
        memset(dest, 0xAA, rec->decoded_len);

        const bool ok = Cps3FirstLight_TestDecodeRecord(buf, buf_size, 256, 0, dest, rec->decoded_len);
        CHECK(ok, "record %u: decode returned false", i);

        if (ok) {
            const int cmp = memcmp(dest, kGoldenDecoded + golden_off, rec->decoded_len);
            CHECK(cmp == 0, "record %u: decoded bytes differ from chardma.py's golden output (%u bytes)", i,
                  rec->decoded_len);
        }

        free(buf);
        free(dest);
        golden_off += rec->decoded_len;
    }

    CHECK(golden_off == sizeof(kGoldenDecoded), "record lengths sum to %u, golden buffer is %zu",
          golden_off, sizeof(kGoldenDecoded));
}

/* 2. All 11 records back-to-back, through the exact call the loader
 *    makes (one shared gfx buffer, dict once, 11 sequential real_source
 *    regions) -- catches any record-boundary state leak (e.g.
 *    m_last_normal_byte carried across records) that sub_a's
 *    per-record isolation could hide. */
static void sub_b_whole_cg(void) {
    g_ran++;

    /* Concatenate: dict [0,256), then each record's compressed bytes
     * back to back, each at its own real_source offset. */
    uint32_t total_compressed = 0;
    for (uint32_t i = 0; i < CG_060A_RECORD_COUNT; i++) {
        total_compressed += kRecords[i].compressed_len;
    }

    uint32_t buf_size = 256 + total_compressed;
    uint8_t* buf = (uint8_t*)malloc(buf_size);

    if (buf == NULL) {
        fprintf(stderr, "[test_cps3_chardma] malloc failed for whole-CG buffer (buf_size=%u)\n", buf_size);
        abort();
    }

    memcpy(buf, kDict, 256);

    uint32_t offsets[CG_060A_RECORD_COUNT];
    uint32_t pos = 256;
    for (uint32_t i = 0; i < CG_060A_RECORD_COUNT; i++) {
        offsets[i] = pos;
        memcpy(buf + pos, kRecords[i].compressed, kRecords[i].compressed_len);
        pos += kRecords[i].compressed_len;
    }

    uint8_t flat[sizeof(kGoldenDecoded)];
    uint32_t flat_off = 0;
    bool all_ok = true;

    for (uint32_t i = 0; i < CG_060A_RECORD_COUNT; i++) {
        const bool ok =
            Cps3FirstLight_TestDecodeRecord(buf, buf_size, offsets[i], 0, flat + flat_off, kRecords[i].decoded_len);
        all_ok = all_ok && ok;
        flat_off += kRecords[i].decoded_len;
    }

    CHECK(all_ok, "whole-CG decode: at least one record returned false");
    CHECK(flat_off == sizeof(kGoldenDecoded), "whole-CG decode produced %u bytes, expected %zu", flat_off,
          sizeof(kGoldenDecoded));
    CHECK(memcmp(flat, kGoldenDecoded, sizeof(kGoldenDecoded)) == 0,
          "whole-CG decode (39 tiles, 9984 bytes) differs from chardma.py's golden output");

    free(buf);
}

/* 3. Cps3FirstLight_NextTile()'s row-major -> Dreamcast-twiddled re-map
 *    (cps3_first_light.c's cps3_first_light_twiddle_tile(), P-1.1 in the
 *    review this test was added for) round-tripped against PPGFile.c's
 *    OWN un-twiddle math (ppgRenewDotDataSeqs() case 0x100). A synthetic
 *    identity tile (tile[y*16+x] = y*16+x) is twiddled by the function
 *    under test, then read back with the exact same
 *    `dctex_linear[j + (i << 5)]` indexing that consumer uses; every
 *    pixel must come back as the row-major value it started as. This is
 *    the case that would have failed before the fix (an un-twiddled/
 *    identity hand-off scrambles every pixel but (0,0)). */
static void sub_c_twiddle_roundtrip(void) {
    g_ran++;

    static uint8_t dctex_linear_test_mem[0x800];
    dctex_linear = (s16*)dctex_linear_test_mem;
    ppgMakeConvTableTexDC();

    uint8_t identity_tile[CPS3_FIRST_LIGHT_TILE_BYTES];
    for (int y = 0; y < 16; y++) {
        for (int x = 0; x < 16; x++) {
            identity_tile[y * 16 + x] = (uint8_t)(y * 16 + x);
        }
    }

    uint8_t twiddled[CPS3_FIRST_LIGHT_TILE_BYTES];
    memset(twiddled, 0xAA, sizeof(twiddled));
    Cps3FirstLight_TestTwiddleTile(identity_tile, twiddled);

    int mismatches = 0;
    for (int i = 0; i < 16; i++) {
        for (int j = 0; j < 16; j++) {
            /* Mirrors PPGFile.c ppgRenewDotDataSeqs() case 0x100 exactly:
             * dstRam8[row i, col j] = srcRam8[dctex_linear[j + (i << 5)]]. */
            const uint8_t got = twiddled[dctex_linear[j + (i << 5)]];
            const uint8_t want = (uint8_t)(i * 16 + j);

            if (got != want) {
                mismatches++;
            }
        }
    }

    CHECK(mismatches == 0, "twiddle round-trip: %d/256 pixels came back through PPGFile.c's own "
                            "un-twiddle at the wrong position",
          mismatches);
}

int Cps3Chardma_Test_Decode(void) {
    printf("=== CPS-3 char-DMA decoder harness (CG 0x060A, doc %s) ===\n", "5S 4.2/5G");

    sub_a_per_record();
    sub_b_whole_cg();
    sub_c_twiddle_roundtrip();

    if (g_ran != EXPECTED_SUBTESTS) {
        printf("COVERAGE FAIL: ran %d sub-test(s), expected exactly %d\n", g_ran, EXPECTED_SUBTESTS);
        return 2;
    }

    if (g_fail != 0) {
        printf("RESULT: FAIL (%d assertion(s))\n", g_fail);
        return 1;
    }

    printf("RESULT: PASS (%d sub-tests; 11 records / 39 tiles / 9984 bytes against chardma.py)\n", g_ran);
    return 0;
}

