/**
 * @file test_cps3_chardma.c
 * Unit harness for the ported CPS-3 char-DMA decoder (cps3_first_light.c),
 * the "first light" scaffolding (docs/research-arcade-cg-data-accuracy.md,
 * ~/Desktop/3s-arm/docs/3sx-rom-only-research.md §5S 4.2).
 *
 * WHY THIS IS THE PASS CRITERION, NOT A LIVE-FRAME COMPARISON. The task
 * asked to "byte-compare the decoded tile bytes against the oracle DMA
 * log" (/Volumes/KimchDrive/3sx-research-logs/cg-dma/run1.dma.log). That
 * log's lines are DMA *command headers* only --
 * "F 1500 DMA list=000400 i=3 cmd=2 src=025a7cec dst=0028d000 len=512
 * d1=... d2=... d3=..." -- src/dst/len metadata, never decoded pixel
 * bytes. There is nothing in it to byte-compare tile PIXELS against.
 * What the log *did* verify (checked once, by hand, against this task's
 * hardcoded kCg060aRecords table in cps3_first_light.c): all 11 of CG
 * 0x060A's cmd=2 records at frame 1500 match this table's (src, len)
 * pairs exactly, in order -- i.e. the loader's record table reproduces
 * live hardware's own DMA burst byte-for-byte at the METADATA level.
 *
 * The nearest available equivalent for the PIXEL level is what this file
 * does: embed the real compressed bytes CG 0x060A's 11 records actually
 * consume (3,208 bytes total, read from the real, verified nr1-revision-
 * equivalent SIMM3-6 image) plus the golden decoded output an
 * INDEPENDENT Python re-implementation (romonly/chardma.py, already used
 * elsewhere in this research to cross-check 1,524 real records) produces
 * for the exact same bytes, and assert the ported C decoder
 * (Cps3FirstLight_TestDecodeRecord) reproduces it bit-exact. This is a
 * decoder-correctness test, not an on-screen-pixels test; no live frame
 * was captured or compared. See the task report for that gap.
 *
 * Provenance of every embedded array: `/Volumes/KimchDrive/3sx-research-
 * logs/cg-dma/rom/romuser.bin` (the assembled 64 MiB SIMM3-6 image,
 * independently built by an earlier research pass) sliced at the 11
 * (src, len) pairs below, decoded once by chardma.py, both sides saved.
 * Separately, this task's own loader (Cps3FirstLight_TryLoad) was run
 * against a real merged sfiii3.zip and reassembled the identical 64 MiB
 * image byte-for-byte before this harness was written (see the task
 * report) -- so the loader and this decoder test share a verified-
 * identical source image, even though this harness embeds only the
 * ~3.5 KB slice it needs rather than shipping 64 MiB in the repo.
 */

